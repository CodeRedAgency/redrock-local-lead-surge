def translate_json_recursive(obj):
    """Recursively translate JSON object"""
    if isinstance(obj, dict):
        return {k: translate_json_recursive(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [translate_json_recursive(item) for item in obj]
    elif isinstance(obj, str):
        return translate_common_phrases(obj)
    else:
        return obj

def translate_file(filepath):
    """Translate a Spanish JSON file"""
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        translated = translate_json_recursive(data)
        
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(translated, f, indent=2, ensure_ascii=False)
        
        return True
    except Exception as e:
        print(f"Error: {filepath}: {e}")
        return False

